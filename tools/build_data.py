"""Generate js/data.js from data extracted out of the original Rampage ROMs.

rom_text.json is produced from pro0/pro1 (Z80 program ROMs): city list at 0x9610,
news headlines/hints at 0x69AC, item names at 0xB2BB, credits at 0xAF30.
Sound files in assets/sfx are the original Sounds Good board output, recorded per
sound code from MAME (see ../analysis/mame_lua/rec_ingame.lua)."""
import json, os, glob
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
d = json.load(open(os.path.join(here, 'rom_text.json')))
codes = sorted(os.path.basename(f)[4:6] for f in glob.glob(os.path.join(root, 'assets/sfx/snd_*.mp3')))
loops = sorted(os.path.basename(f)[4:6] for f in glob.glob(os.path.join(root, 'assets/sfx/snd_*.wav')))
out = ["// Generated by tools/build_data.py from the original ROM data. Do not edit by hand.",
       "export const CITIES = " + json.dumps(d['cities']) + ";",
       "export const HEADLINES = " + json.dumps(d['headlines']) + ";",
       "export const ROM_ITEMS = " + json.dumps(d['items']) + ";",
       "export const ROM_CREDITS = " + json.dumps(d['credits']) + ";",
       "export const SFX_CODES = " + json.dumps(codes) + ";",
       "export const SFX_WAV = " + json.dumps(loops) + ";", ""]
open(os.path.join(root, 'js/data.js'), 'w').write("\n".join(out))
print('cities', len(d['cities']), 'headlines', len(d['headlines']), 'sfx', len(codes))
